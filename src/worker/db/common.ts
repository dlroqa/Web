import { z } from "../../shared/zod";
import { UnexpectedDbError } from "./errors";

export type Clock = () => number;
export const systemClock: Clock = () => Date.now();

export interface RepositoryOptions {
  now?: Clock;
}

/** Validate a row read from D1 before it becomes a domain object. */
export function parseRow<S extends z.ZodType>(schema: S, row: unknown): z.output<S> {
  const parsed = schema.safeParse(row);
  if (!parsed.success) throw new UnexpectedDbError("stored row failed validation");
  return parsed.data;
}

export const Timestamp = z.number().int().positive();
export const NullableTimestamp = Timestamp.nullable();

/** Prefixed random id as generated by utils/random.ts. */
export function idSchema(prefix: string) {
  return z.string().regex(new RegExp(`^${prefix}_[a-z0-9]{8,59}$`));
}

/** User-supplied names: trimmed, 1–80 chars, no control characters. */
export const NameSchema = z
  .string()
  .trim()
  .min(1)
  .max(80)
  .refine((value) => !/[\u0000-\u001f\u007f]/.test(value), "control characters are not allowed");
